func TestImportGitHub_BasicCommits(t *testing.T) {
	repo := setupGitRepo(t, "test@example.com", "Tester", []commitSpec{
		{msg: "Add initial feature", date: "2023-11-14T15:00:00+00:00"},
		{msg: "Fix a bug in the feature", date: "2023-11-14T16:00:00+00:00"},
	})

	result, err := ImportGitHub(GitHubImportOptions{Repos: []string{repo}})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(result) != 2 {
		t.Fatalf("expected 2 commits, got %d", len(result))
	}
	if result[0].Text != "Add initial feature" {
		t.Errorf("expected 'Add initial feature', got %q", result[0].Text)
	}
	if result[0].Metadata["repo"] != filepath.Base(repo) {
		t.Errorf("expected repo name %q, got %v", filepath.Base(repo), result[0].Metadata["repo"])
	}
}

func TestImportGitHub_EmailFilter(t *testing.T) {
	repo := t.TempDir()
	initGitRepo(t, repo)

	// commit from two different authors
	gitCommit(t, repo, "me@example.com", "Me", "My commit", "2023-11-14T15:00:00+00:00")
	gitCommit(t, repo, "other@example.com", "Other", "Other commit", "2023-11-14T16:00:00+00:00")

	result, err := ImportGitHub(GitHubImportOptions{
		Repos: []string{repo},
		Email: "me@example.com",
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(result) != 1 {
		t.Fatalf("expected 1 commit, got %d", len(result))
	}
	if result[0].Text != "My commit" {
		t.Errorf("expected 'My commit', got %q", result[0].Text)
	}
}

func TestImportGitHub_AutoGeneratedFiltering(t *testing.T) {
	tests := []struct {
		subject  string
		filtered bool
	}{
		{"Merge pull request #42 from someone/branch", true},
		{"Merge branch 'main' into feature", true},
		{"Revert \"Some change\"", true},
		{"Auto-merge something", true},
		{"Initial commit", true},
		{"Co-Authored-By: someone", true},
		{"Bump lodash from 4.17.20 to 4.17.21", true},
		{"chore(deps): update dependency", true},
		{"fix: resolve login issue", false},
		{"Add new endpoint for users", false},
	}

	for _, tc := range tests {
		got := isAutoGenerated(tc.subject)
		if got != tc.filtered {
			t.Errorf("isAutoGenerated(%q) = %v, want %v", tc.subject, got, tc.filtered)
		}
	}
}

func TestImportGitHub_SinceFilter(t *testing.T) {
	repo := setupGitRepo(t, "test@example.com", "Tester", []commitSpec{
		{msg: "Old commit", date: "2020-01-01T00:00:00+00:00"},
		{msg: "New commit", date: "2023-11-14T15:00:00+00:00"},
	})

	since := time.Date(2023, 1, 1, 0, 0, 0, 0, time.UTC)
	result, err := ImportGitHub(GitHubImportOptions{
		Repos: []string{repo},
		Since: &since,
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(result) != 1 {
		t.Fatalf("expected 1 commit, got %d", len(result))
	}
	if result[0].Text != "New commit" {
		t.Errorf("expected 'New commit', got %q", result[0].Text)
	}
}

func TestImportGitHub_CommitWithBody(t *testing.T) {
	repo := t.TempDir()
	initGitRepo(t, repo)

	// commit with subject and body
	gitCommitWithBody(t, repo, "test@example.com", "Tester",
		"Add feature X\n\nThis adds feature X with support\nfor multiple lines.",
		"2023-11-14T15:00:00+00:00")

	result, err := ImportGitHub(GitHubImportOptions{Repos: []string{repo}})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(result) != 1 {
		t.Fatalf("expected 1 commit, got %d", len(result))
	}
	if !contains(result[0].Text, "Add feature X") {
		t.Errorf("expected subject in text, got %q", result[0].Text)
	}
	if !contains(result[0].Text, "This adds feature X") {
		t.Errorf("expected body in text, got %q", result[0].Text)
	}
}

